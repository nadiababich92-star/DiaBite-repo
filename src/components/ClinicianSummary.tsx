import { useEffect, useMemo, useRef, useState } from 'react'
import { buildSummary, DEFAULT_PERIOD, SUMMARY_PERIODS, type SummaryDay, type SummaryPeriod } from '../lib/clinicianSummary'
import { MEAL_LABELS } from '../lib/menu'
import { useToday } from '../lib/useToday'
import type { DiaryEntry, Profile, Targets } from '../types'

/**
 * "Summary for my clinician": a page the person prints, or saves as PDF, to show a dietitian or doctor.
 * Spec: docs/specs/clinician-summary-screen.md. Rendered alone by App (no masthead, no tabs), so only this prints.
 *
 * Every figure is `buildSummary`'s (the Diary's own arithmetic); this file only lays it out. The two DRAFT texts
 * (the Settings card sentence, in SettingsPage, and "How to read this" below) are not final until agreed in chat.
 */
interface Props { diary: DiaryEntry[]; profile: Profile; targets: Targets; onClose: () => void }

/** "Nov 17, 2026" from YYYY-MM-DD, in the person's own calendar. */
const longDate = (iso: string) => {
  const [y, m, d] = iso.split('-').map(Number)
  return new Date(y, m - 1, d).toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' })
}
const shortDate = (iso: string) => {
  const [y, m, d] = iso.split('-').map(Number)
  return new Date(y, m - 1, d).toLocaleDateString('en-US', { month: 'short', day: 'numeric' })
}

/** The notes cell of a day, in the order the spec gives. */
const notesOf = (d: SummaryDay): string => [
  d.isToday ? 'today, so far' : '',
  d.estimate ? 'estimate' : '',
  d.noLoadFoods > 0 ? `${d.noLoadFoods} ${d.noLoadFoods === 1 ? 'food has' : 'foods have'} no glycemic load, not counted` : '',
  d.slots < 3 ? `fewer than 3 meals (${d.slots} of 4)` : '',
].filter(Boolean).join('; ')

/** A figure with its word: "142 · over". Bold on over, so the meaning is a word and never only a colour. */
const Said = ({ value, word }: { value: number; word: string }) => (
  <><span className="num">{value}</span> · {word === 'over' ? <b>over</b> : word}</>
)

// DRAFT TO BE AGREED IN CHAT, not final copy.
const HOW_TO_READ_DRAFT = "The numbers come from DiaBite's food data and were added up by the app; no one at DiaBite typed them, and none were generated by a language model. Carbohydrate is total carbohydrate. Glycemic load is missing for some foods, such as packaged products; a day that includes one says so and is not called 'not over'. 'Estimate' means a dish was counted from an assumed recipe. Targets are DiaBite's calculation unless marked as set by you and your doctor. DiaBite does not give medical advice and does not dose or adjust insulin."

export default function ClinicianSummary({ diary, profile, targets, onClose }: Props) {
  const today = useToday()
  const [period, setPeriod] = useState<SummaryPeriod>(DEFAULT_PERIOD)
  const [name, setName] = useState('')
  const s = useMemo(() => buildSummary(diary, profile, targets, today, period), [diary, profile, targets, today, period])
  const heading = useRef<HTMLHeadingElement>(null)

  // The saved PDF gets a useful file name. The typed name is never put in the title.
  useEffect(() => {
    const before = document.title
    document.title = `DiaBite summary ${s.from} to ${s.to}`
    return () => { document.title = before }
  }, [s.from, s.to])

  useEffect(() => { heading.current?.focus() }, [])
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => { if (e.key === 'Escape') onClose() }
    document.addEventListener('keydown', onKey)
    return () => document.removeEventListener('keydown', onKey)
  }, [onClose])

  const empty = s.loggedDays === 0
  // Days and the runs with nothing logged, newest first, so a gap sits where it happened.
  const rows = useMemo(() => [
    ...s.days.map((day) => ({ kind: 'day' as const, date: day.date, day })),
    ...s.notLogged.map((r) => ({ kind: 'gap' as const, date: r.to, from: r.from, to: r.to })),
  ].sort((a, b) => (a.date < b.date ? 1 : -1)), [s])

  return (
    <div className="summary-root">
      <div className="summary-bar no-print">
        <div className="row" role="group" aria-label="Period">
          {SUMMARY_PERIODS.map((p) => (
            <button key={p} className="ghost" aria-pressed={period === p} onClick={() => setPeriod(p)}>{p} days</button>
          ))}
        </div>
        <label className="summary-name">
          <span>Name (optional, printed, not saved)</span>
          <input type="text" value={name} maxLength={80} autoComplete="off" onChange={(e) => setName(e.target.value)} />
        </label>
        <div className="row">
          <button className="primary" onClick={() => window.print()} disabled={empty}>Print or save as PDF</button>
          <button className="ghost" onClick={onClose}>Close</button>
        </div>
      </div>

      <article className="summary" aria-labelledby="sum-title">
        <h1 id="sum-title" tabIndex={-1} ref={heading}>DiaBite summary</h1>
        <p>{shortDate(s.from)} to {longDate(s.to)}, {s.periodDays} days. Printed {longDate(s.printedOn)}.</p>
        <p className="summary-name-line">Name: {name.trim() === '' ? <span className="summary-blank" aria-hidden="true" /> : name}</p>

        <h2>About this person</h2>
        <p>
          {s.about.condition}. {s.about.insulin[0].toUpperCase() + s.about.insulin.slice(1)}.{' '}
          {s.about.medicines.length > 0 ? `Medicines: ${s.about.medicines.join(', ')}.` : 'No glucose-lowering medicine listed.'}
        </p>

        <h2>Targets</h2>
        <table>
          <caption>Targets as of {longDate(s.printedOn)}</caption>
          <thead><tr><th scope="col">Target</th><th scope="col">Per day</th><th scope="col">Set by</th></tr></thead>
          <tbody>
            <tr><th scope="row">Energy</th><td className="num">{s.targets.kcal} kcal</td><td>calculated by DiaBite</td></tr>
            <tr><th scope="row">Carbohydrate</th><td className="num">{s.targets.carbsG} g</td><td>{s.targets.carbsSetBy === 'person' ? 'set by you and your doctor or dietitian' : 'calculated by DiaBite'}</td></tr>
            <tr><th scope="row">Fibre</th><td className="num">{s.targets.fiberG} g</td><td>calculated by DiaBite</td></tr>
            <tr><th scope="row">Protein</th><td className="num">{s.targets.proteinG} g</td><td>calculated by DiaBite</td></tr>
            <tr><th scope="row">Fat</th><td className="num">{s.targets.fatG} g</td><td>calculated by DiaBite</td></tr>
            <tr><th scope="row">Glycemic load</th><td className="num">{s.targets.glBudget}</td><td>calculated by DiaBite</td></tr>
          </tbody>
        </table>
        {(s.targets.mealCarbsG !== null || s.targets.snackCarbsG !== null) && (
          <p>
            Your own numbers: {[
              s.targets.mealCarbsG !== null ? `${s.targets.mealCarbsG} g carbohydrate a meal` : null,
              s.targets.snackCarbsG !== null ? `${s.targets.snackCarbsG} g a snack` : null,
            ].filter(Boolean).join(' and ')}, from your doctor or dietitian.
          </p>
        )}

        <h2>The days</h2>
        {empty ? (
          <p>Nothing logged in the last {s.periodDays} days. Log what you eat and come back.</p>
        ) : (
          <>
            {s.loggedDays < 3 && <p>Only {s.loggedDays} of {s.periodDays} days were logged.</p>}
            <p className="muted" aria-hidden="true">Totals for each logged day. Carbohydrate is total carbohydrate; fibre is shown beside it.</p>
            <div className="summary-scroll">
              <table className="summary-days">
                <caption className="sr-only">Totals for each logged day. Carbohydrate is total carbohydrate; fibre is shown beside it.</caption>
                <thead>
                  <tr>
                    <th scope="col">Day</th><th scope="col">Energy (kcal)</th><th scope="col">Carbs (total, g)</th><th scope="col">Fibre (g)</th>
                    <th scope="col">Protein (g)</th><th scope="col">Fat (g)</th><th scope="col">Glycemic load</th><th scope="col">Notes</th>
                  </tr>
                  <tr className="summary-target">
                    <th scope="row">Target</th><td className="num">{s.targets.kcal}</td><td className="num">{s.targets.carbsG}</td><td className="num">{s.targets.fiberG}</td>
                    <td className="num">{s.targets.proteinG}</td><td className="num">{s.targets.fatG}</td><td className="num">{s.targets.glBudget}</td><td />
                  </tr>
                </thead>
                <tbody>
                  {rows.map((r) => r.kind === 'gap' ? (
                    <tr key={`g${r.date}`} className="summary-gap"><td colSpan={8}>{r.from === r.to ? shortDate(r.from) : `${shortDate(r.from)} to ${shortDate(r.to)}`}: not logged</td></tr>
                  ) : (
                    <tr key={r.day.date}>
                      <th scope="row">{r.day.label}</th>
                      <td><Said value={r.day.kcal} word={r.day.kcalVerdict} /></td>
                      <td><Said value={r.day.carbs} word={r.day.carbsVerdict} /></td>
                      <td className="num">{r.day.fiber}</td><td className="num">{r.day.protein}</td><td className="num">{r.day.fat}</td>
                      <td><Said value={r.day.gl} word={r.day.glVerdict} /></td>
                      <td>{notesOf(r.day)}</td>
                    </tr>
                  ))}
                </tbody>
                {s.averages && (
                  <tfoot>
                    <tr>
                      <th scope="row">Average of {s.loggedDays} logged {s.loggedDays === 1 ? 'day' : 'days'}</th>
                      <td className="num">{s.averages.kcal}</td><td className="num">{s.averages.carbs}</td><td className="num">{s.averages.fiber}</td>
                      <td className="num">{s.averages.protein}</td><td className="num">{s.averages.fat}</td><td className="num">{s.averages.gl}</td><td />
                    </tr>
                  </tfoot>
                )}
              </table>
            </div>

            <h2>Meals</h2>
            {s.days.map((d) => (
              <section key={d.date} className="summary-meals">
                <h3>{d.label}</h3>
                {d.meals.map((m) => (
                  <div key={m.meal}>
                    <h4>{MEAL_LABELS[m.meal]}</h4>
                    <ul>
                      {m.items.map((i, k) => (
                        <li key={k}>{i.name} · {i.portion} · <span className="num">{i.carbs}</span> g carbs · GL <span className="num">{i.gl === null ? '—' : i.gl}</span>{i.estimate ? ' · estimate' : ''}</li>
                      ))}
                    </ul>
                  </div>
                ))}
              </section>
            ))}
          </>
        )}

        <h2>How to read this</h2>
        {/* DRAFT TO BE AGREED IN CHAT, not final copy. */}
        <p data-draft>{HOW_TO_READ_DRAFT}</p>

        <p className="summary-footer">DiaBite · diabite.pro · printed {longDate(s.printedOn)}</p>
      </article>
    </div>
  )
}
